ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS role text NOT NULL DEFAULT 'developer';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'projects_role_check'
      AND conrelid = 'public.projects'::regclass
  ) THEN
    ALTER TABLE public.projects
      ADD CONSTRAINT projects_role_check
      CHECK (role IN ('developer', 'illustrator', 'both'));
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.experiences (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category text NOT NULL CHECK (category IN ('work', 'organization')),
  role text NOT NULL DEFAULT 'developer'
    CHECK (role IN ('developer', 'illustrator', 'both')),
  organization text NOT NULL,
  position text NOT NULL,
  description text,
  start_date date NOT NULL,
  end_date date,
  is_current boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS experiences_start_date_idx
  ON public.experiences (start_date DESC);

ALTER TABLE public.experiences ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'experiences'
      AND policyname = 'public read experiences'
  ) THEN
    CREATE POLICY "public read experiences"
      ON public.experiences
      FOR SELECT
      USING (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'experiences'
      AND policyname = 'admin manage experiences'
  ) THEN
    CREATE POLICY "admin manage experiences"
      ON public.experiences
      FOR ALL
      TO authenticated
      USING (
        EXISTS (
          SELECT 1
          FROM public.profiles
          WHERE id = auth.uid()
            AND role = 'admin'
        )
      )
      WITH CHECK (
        EXISTS (
          SELECT 1
          FROM public.profiles
          WHERE id = auth.uid()
            AND role = 'admin'
        )
      );
  END IF;
END
$$;
